void HAL_I2C_MspInit(I2C_HandleTypeDef *hi2c)
{
  GPIO_InitTypeDef GPIO_InitStruct = {0};
  RCC_PeriphCLKInitTypeDef PeriphClkInit = {0};

  if (hi2c->Instance == I2C1)
  {
    /* Keep the selected HSI16 peripheral kernel requested during recovery. */
    SET_BIT(RCC->CR, RCC_CR_HSIKERON);
    PeriphClkInit.PeriphClockSelection = RCC_PERIPHCLK_I2C1;
    PeriphClkInit.I2c1ClockSelection = RCC_I2C1CLKSOURCE_HSI;
    if (HAL_RCCEx_PeriphCLKConfig(&PeriphClkInit) != HAL_OK)
    {
      Error_Handler();
    }
    __HAL_RCC_GPIOB_CLK_ENABLE();
    /* PCB: PB8=U2 SCL, PB9=U2 SDA. Existing R302/R303 pull up to 3V3D. */
    GPIO_InitStruct.Pin = BMS_SCL_Pin | BMS_SDA_Pin;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_OD;
    /* Bring-up: weak MCU pull-ups keep PB8/PB9 released on this board.
     * External SCL pull-up path still needs physical verification. */
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
    GPIO_InitStruct.Alternate = GPIO_AF4_I2C1;
    HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);
    __HAL_RCC_I2C1_CLK_ENABLE();
  }
}

void HAL_I2C_MspDeInit(I2C_HandleTypeDef *hi2c)
{
  if (hi2c->Instance == I2C1)
  {
    __HAL_RCC_I2C1_CLK_DISABLE();
    HAL_GPIO_DeInit(GPIOB, BMS_SCL_Pin | BMS_SDA_Pin);
  }
}

